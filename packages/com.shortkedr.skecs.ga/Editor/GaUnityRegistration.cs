using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SKECS.GA.Unity.Editor
{
    internal static class GaUnityRegistration
    {
        internal static string Emit(GaProgram program, GaContractIdentity contract, string name, string input, string resource)
        {
            var code = new StringBuilder();
            string rows = "@" + name + "Rows";
            string cpu = "@" + name + "Cpu";
            string generic = input is null ? "<TInput>" : "";
            string constraint = input is null ? " where TInput : unmanaged" : "";
            string frame = input ?? "TInput";
            void Line(string value) => code.AppendLine(value);

            Line("// <auto-generated/>");
            Line("#nullable enable");
            Line("using System;");
            Line("using System.Linq;");
            Line("using SKECS;");
            Line("using SKECS.GA;");
            Line("using SKECS.GA.Unity;");
            Line($"internal static class @{name}");
            Line("{");
            Line("    internal static GaContractIdentity Contract { get; } = new GaContractIdentity(");
            Line($"        {rows}.SystemId, {Literal(contract.SimulationContractId)}, {rows}.SourceDigest,");
            Line($"        {rows}.IrDigest, {rows}.ComponentSchemaDigest, {Number(contract.NumericVersion)},");
            Line($"        {Number(contract.SubsetVersion)}, {Number(contract.IrVersion)})");
            Line("    {");
            foreach (string property in new[] { "EventCapacity", "UsesSnapshot", "SnapshotSchema", "TickResourceType",
                "TickResourceWords", "BufferSchema", "BufferRowWords", "UsesCommands", "AdditionPayloadWords",
                "EventTypeCount", "EventPayloadWords", "ReductionTypeCount", "UsesDomainOrder" })
                Line($"        {property} = {rows}.{property},");
            Line($"        ComponentRemovalCount = {Number(contract.ComponentRemovalCount)},");
            Line($"        ComponentAdditionCount = {Number(contract.ComponentAdditionCount)},");
            Line("    };");
            Line($"    internal static GaUnityKernelAsset LoadAsset() => UnityEngine.Resources.Load<GaUnityKernelAsset>({Literal(resource)});");
            Line("    internal static GaSystemRequest CreateRequest(GaUnityKernelAsset? asset) => asset");
            Line("        ? asset!.CreateRequest(Contract) : new GaSystemRequest(Contract, Array.Empty<GaArtifactCandidate>());");

            var bindings = new List<(string Type, string Name)>();
            if (program.BufferSchema is not null)
                bindings.Add(("GaTickBuffer", "buffer"));
            if (program.UsesSnapshot)
                bindings.Add(("GaTickSnapshot", "snapshot"));
            var reductions = program.EventTypes.Select((item, index) => (item, index)).Where(entry => entry.item.IsContribution).ToArray();
            foreach (var entry in reductions)
                bindings.Add(($"DeterministicReduction<{entry.item.Id}>", "reduction" + Number(entry.index)));
            string events = reductions.Length == 0 ? $"{rows}.EventTypes" :
                $"{rows}.CreateEventTypes({string.Join(", ", reductions.Select(entry => "reduction" + Number(entry.index)))})";
            if (!program.UsesDomainOrder)
                Register(grouped: false);
            Register(grouped: true);
            Line("}");
            return code.ToString();

            void Register(bool grouped)
            {
                string ownerType = grouped ? "DeterministicCommitGroup" : "DeterministicWorkload";
                string stageParameter = grouped ? "" : ", SystemStage stage";
                string stageArgument = grouped ? "" : ", stage";
                string stagePrefix = grouped ? "" : "stage, ";
                string extraParameters = string.Concat(bindings.Select(value => $", {value.Type} {value.Name}"));
                string extraArguments = string.Concat(bindings.Select(value => ", " + value.Name));
                string snapshot = program.UsesSnapshot ? "snapshot" : "null";
                string buffer = program.BufferSchema is not null ? "buffer" : "null";
                string resourceCodec = program.TickResourceType is not null ? $"{rows}.TickResource" : "default";
                string cpuGeneric = program.TickResourceType is null ? $"<{frame}>" : "";
                Line("");
                Line($"    internal static {ownerType}<{frame}> Register{generic}(");
                Line($"        {ownerType}<{frame}> owner{stageParameter}, GaStartupResult startup{extraParameters},");
                Line($"        DeterministicSourceOrder? sourceOrder = null, Action<GaBatchTimings>? observe = null){constraint}");
                Line("    {");
                Line($"        var decision = startup.Decisions.Single(item => item.Contract.SystemId == {rows}.SystemId);");
                Line("        if (!startup.Succeeded || decision.Contract != Contract)");
                Line("            throw new InvalidOperationException(\"The selected GA plan does not match this generated registration.\");");
                Line("        if (decision.Route == GaRoute.Cpu)");
                Line($"            return {cpu}.Register{cpuGeneric}(owner{stageArgument}{extraArguments}, sourceOrder);");
                Line($"        var processor = new GaBatchProcessor<{frame}>(startup, {rows}.SystemId, {rows}.SourceDigest,");
                Line($"            {rows}.IrDigest, {rows}.ComponentSchemaDigest, {rows}.WordsPerRow,");
                Line($"            {rows}.Pack<{frame}>, {rows}.Apply<{frame}>, {rows}.EventCapacity, observe, {snapshot},");
                Line($"            {rows}.UsesCommands, {rows}.ComponentRemovals, {rows}.ComponentAdditions, {resourceCodec},");
                Line($"            {buffer}, {events});");
                Line($"        return owner.AddBatchSystem({stagePrefix}{rows}.CreateQuery(sourceOrder), processor);");
                Line("    }");
            }
        }

        private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
    }
}
