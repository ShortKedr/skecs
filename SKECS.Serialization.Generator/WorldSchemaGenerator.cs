using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SKECS.Serialization.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class WorldSchemaGenerator : IIncrementalGenerator
{
    private const string ComponentAttribute = "SKECS.Serialization.WorldComponentAttribute";
    private const string FieldAttribute = "SKECS.Serialization.WorldFieldAttribute";
    private const string IgnoreAttribute = "SKECS.Serialization.WorldIgnoreAttribute";

    private static readonly DiagnosticDescriptor InvalidComponent = Error("001", "Invalid world component",
        "Component '{0}' must be an accessible non-generic unmanaged struct with ordinary field layout");
    private static readonly DiagnosticDescriptor InvalidIdentity = Error("002", "Invalid schema identity",
        "Component '{0}' must declare a positive stable ID and version");
    private static readonly DiagnosticDescriptor DuplicateId = Error("003", "Duplicate stable component ID",
        "Component '{0}' declares stable ID {1}, which is already used by another component");
    private static readonly DiagnosticDescriptor MissingField = Error("004", "Unmarked component field",
        "Field '{0}' must declare WorldField or WorldIgnore");
    private static readonly DiagnosticDescriptor InvalidField = Error("005", "Unsupported component field",
        "Field '{0}' must be an accessible writable instance field of a supported scalar, enum, Entity, or Fixed (numeric contract 1) type");
    private static readonly DiagnosticDescriptor InvalidTag = Error("006", "Invalid field tag",
        "Field '{0}' must declare a positive stable tag");
    private static readonly DiagnosticDescriptor DuplicateTag = Error("007", "Duplicate stable field tag",
        "Field '{0}' declares tag {1}, which is already used by another field of its component");
    private static readonly DiagnosticDescriptor ConflictingAttributes = Error("008", "Conflicting field attributes",
        "Field '{0}' cannot declare both WorldField and WorldIgnore");

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(ComponentAttribute,
            static (node, _) => node is TypeDeclarationSyntax,
            static (attribute, _) => (INamedTypeSymbol)attribute.TargetSymbol);
        context.RegisterSourceOutput(candidates.Collect(), Emit);
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> candidates)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var components = new List<Component>();
        var identities = new Dictionary<uint, List<INamedTypeSymbol>>();
        var valid = true;
        foreach (var type in candidates)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            if (!seen.Add(type)) continue;

            var attribute = Find(type, ComponentAttribute)!;
            var id = Identity(attribute);
            var version = 1u;
            foreach (var option in attribute.NamedArguments)
                if (option.Key == "Version") version = option.Value.Value is uint value ? value : 0;

            if (id != 0) Track(identities, id, type);
            if (id == 0 || version == 0)
            {
                Report(context, InvalidIdentity, type, type);
                valid = false;
            }

            if (!IsSupportedComponent(type))
            {
                Report(context, InvalidComponent, type, type);
                valid = false;
                continue;
            }

            var fields = ReadFields(context, type);
            if (fields is null) valid = false;
            else components.Add(new Component(type, id, version, fields));
        }

        valid &= CheckDuplicates(context, identities, DuplicateId);
        if (!valid || components.Count == 0) return;

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("namespace SKECS.Serialization.Generated");
        source.AppendLine("{");
        source.AppendLine("    internal static class WorldSchema");
        source.AppendLine("    {");
        source.AppendLine("        public static global::SKECS.Serialization.CodecRegistry Create()");
        source.AppendLine("        {");
        source.AppendLine("            var registry = new global::SKECS.Serialization.CodecRegistry();");
        components.Sort((left, right) => left.Id.CompareTo(right.Id));
        foreach (var component in components)
            EmitRegistration(source, component);
        source.AppendLine("            return registry;");
        source.AppendLine("        }");
        foreach (var component in components)
            EmitCodec(source, component);
        source.AppendLine("    }");
        source.AppendLine("}");
        context.AddSource("WorldSchema.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static bool IsSupportedComponent(INamedTypeSymbol type)
    {
        if (type.TypeKind != TypeKind.Struct || !type.IsUnmanagedType || type.IsRefLikeType ||
            Find(type, "System.Runtime.CompilerServices.InlineArrayAttribute") is not null)
            return false;

        var layout = Find(type, "System.Runtime.InteropServices.StructLayoutAttribute");
        if (layout is not null && layout.ConstructorArguments.Length == 1 &&
            layout.ConstructorArguments[0].Value is 2 or (short)2)
            return false;

        for (var declaring = type; declaring is not null; declaring = declaring.ContainingType)
            if (declaring.Arity != 0 || declaring.IsFileLocal || !IsAccessible(declaring)) return false;
        return true;
    }

    private static List<Field>? ReadFields(SourceProductionContext context, INamedTypeSymbol type)
    {
        var fields = new List<Field>();
        var tags = new Dictionary<uint, List<IFieldSymbol>>();
        var valid = true;
        foreach (var symbol in type.GetMembers().OfType<IFieldSymbol>())
        {
            var field = Find(symbol, FieldAttribute);
            var ignore = Find(symbol, IgnoreAttribute);
            if (field is not null && ignore is not null)
            {
                Report(context, ConflictingAttributes, symbol, DisplayField(symbol));
                valid = false;
                continue;
            }
            if (ignore is not null || symbol.IsStatic && field is null) continue;
            if (field is null)
            {
                Report(context, MissingField, symbol, DisplayField(symbol));
                valid = false;
                continue;
            }

            var tag = Identity(field);
            if (tag == 0)
            {
                Report(context, InvalidTag, symbol, DisplayField(symbol));
                valid = false;
            }
            else Track(tags, tag, symbol);

            var enumType = (symbol.Type as INamedTypeSymbol)?.EnumUnderlyingType;
            var isFixed = Qualified(symbol.Type) == "global::SKECS.Numerics.Fixed" && symbol.Type
                .GetMembers("NumericContractVersion").OfType<IFieldSymbol>().Any(member => member.ConstantValue is 1);
            var kind = isFixed ? "Int64" : GetKind(enumType ?? symbol.Type);
            if (kind is null || symbol.IsStatic || symbol.IsReadOnly || symbol.IsFixedSizeBuffer ||
                symbol.IsImplicitlyDeclared || !IsAccessible(symbol))
            {
                Report(context, InvalidField, symbol, DisplayField(symbol));
                valid = false;
                continue;
            }

            fields.Add(new Field(symbol, tag, kind, enumType, isFixed));
        }

        valid &= CheckDuplicates(context, tags, DuplicateTag);
        fields.Sort((left, right) => left.Tag.CompareTo(right.Tag));
        return valid ? fields : null;
    }

    private static ISymbol DisplayField(IFieldSymbol field) => field.AssociatedSymbol ?? field;

    private static string? GetKind(ITypeSymbol type) => type.SpecialType switch
    {
        SpecialType.System_Boolean => "Boolean",
        SpecialType.System_SByte => "Int8",
        SpecialType.System_Byte => "UInt8",
        SpecialType.System_Int16 => "Int16",
        SpecialType.System_UInt16 => "UInt16",
        SpecialType.System_Int32 => "Int32",
        SpecialType.System_UInt32 => "UInt32",
        SpecialType.System_Int64 => "Int64",
        SpecialType.System_UInt64 => "UInt64",
        SpecialType.System_Single => "Float32",
        SpecialType.System_Double => "Float64",
        _ => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == "global::SKECS.Entity" ? "Entity" : null
    };

    private static bool IsAccessible(ISymbol symbol) => symbol.DeclaredAccessibility is
        Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal;

    private static AttributeData? Find(ISymbol symbol, string name) =>
        symbol.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == name);

    private static uint Identity(AttributeData attribute) =>
        attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is uint id ? id : 0;

    private static void Track<T>(Dictionary<uint, List<T>> uses, uint id, T symbol)
    {
        if (!uses.TryGetValue(id, out var symbols)) uses.Add(id, symbols = new List<T>());
        symbols.Add(symbol);
    }

    private static bool CheckDuplicates<T>(SourceProductionContext context, Dictionary<uint, List<T>> uses,
        DiagnosticDescriptor descriptor) where T : ISymbol
    {
        var unique = true;
        foreach (var pair in uses)
        {
            if (pair.Value.Count == 1) continue;
            unique = false;
            foreach (var symbol in pair.Value) Report(context, descriptor, symbol, symbol, pair.Key);
        }
        return unique;
    }

    private static DiagnosticDescriptor Error(string id, string title, string message) =>
        new DiagnosticDescriptor("SKECSSER" + id, title, message, "SKECS.Serialization", DiagnosticSeverity.Error, true);

    private static void Report(SourceProductionContext context, DiagnosticDescriptor descriptor, ISymbol symbol,
        params object[] arguments)
    {
        if (symbol is IFieldSymbol field) symbol = DisplayField(field);
        context.ReportDiagnostic(Diagnostic.Create(descriptor, symbol.Locations.FirstOrDefault(), arguments));
    }

    private static string Number(uint value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Qualified(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    private static void EmitRegistration(StringBuilder source, Component component)
    {
        var id = Number(component.Id);
        source.Append("            registry.Register<").Append(Qualified(component.Type)).AppendLine(">(");
        source.Append("                new global::SKECS.ComponentSchema(").Append(id).Append("u, ")
            .Append(Number(component.Version)).Append("u");
        foreach (var field in component.Fields)
        {
            source.AppendLine(",");
            source.Append("                    new global::SKECS.FieldSchema(").Append(Number(field.Tag))
                .Append("u, global::SKECS.FieldKind.").Append(field.Kind).Append(')');
        }
        source.AppendLine("),");
        source.Append("                new Codec").Append(id).AppendLine("());");
    }

    private static void EmitCodec(StringBuilder source, Component component)
    {
        var type = Qualified(component.Type);
        source.AppendLine();
        source.Append("        private sealed class Codec").Append(Number(component.Id))
            .Append(" : global::SKECS.Serialization.IComponentCodec<").Append(type).AppendLine(">");
        source.AppendLine("        {");
        source.Append("            public void Write(in ").Append(type)
            .AppendLine(" value, global::SKECS.Serialization.ComponentWriter fields)");
        source.AppendLine("            {");
        foreach (var field in component.Fields)
        {
            var tag = Number(field.Tag) + "u";
            var value = "value.@" + field.Symbol.Name;
            if (field.Kind == "Entity")
                source.Append("                fields.SetEntity(").Append(tag).Append(", ").Append(value).AppendLine(");");
            else
            {
                if (field.IsFixed) value += ".Raw";
                else if (field.EnumType is not null) value = "(" + Qualified(field.EnumType) + ")" + value;
                source.Append("                fields.Set(").Append(tag).Append(", global::SKECS.Serialization.FieldValue.From(")
                    .Append(value).AppendLine("));");
            }
        }
        source.AppendLine("            }");
        source.AppendLine();
        source.Append("            public ").Append(type).AppendLine(" Read(global::SKECS.Serialization.ComponentReader fields)");
        source.AppendLine("            {");
        source.Append("                var value = default(").Append(type).AppendLine(");");
        foreach (var field in component.Fields)
        {
            var tag = Number(field.Tag) + "u";
            var value = field.Kind == "Entity" ? $"fields.GetEntity({tag})" : $"fields.Get({tag}).As{field.Kind}()";
            if (field.IsFixed) value = $"global::SKECS.Numerics.Fixed.FromRaw({value})";
            else if (field.EnumType is not null) value = $"({Qualified(field.Symbol.Type)}){value}";
            source.Append("                value.@").Append(field.Symbol.Name).Append(" = ").Append(value).AppendLine(";");
        }
        source.AppendLine("                return value;");
        source.AppendLine("            }");
        source.AppendLine("        }");
    }

    private sealed class Component
    {
        public Component(INamedTypeSymbol type, uint id, uint version, List<Field> fields)
        {
            Type = type;
            Id = id;
            Version = version;
            Fields = fields;
        }

        public INamedTypeSymbol Type { get; }
        public uint Id { get; }
        public uint Version { get; }
        public List<Field> Fields { get; }
    }

    private sealed class Field
    {
        public Field(IFieldSymbol symbol, uint tag, string kind, ITypeSymbol? enumType, bool isFixed)
        {
            Symbol = symbol;
            Tag = tag;
            Kind = kind;
            EnumType = enumType;
            IsFixed = isFixed;
        }

        public IFieldSymbol Symbol { get; }
        public uint Tag { get; }
        public string Kind { get; }
        public ITypeSymbol? EnumType { get; }
        public bool IsFixed { get; }
    }
}
