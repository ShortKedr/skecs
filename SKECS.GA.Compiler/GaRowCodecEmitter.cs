using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SKECS.GA;

/// <summary>Emits typed packing and writeback for the canonical rows of a deterministic job.</summary>
public static class GaRowCodecEmitter
{
    public static string Emit(GaProgram program, string className = "GaRowCodec") =>
        Emit(program, className, unityCompatible: false);

    /// <summary>Emits a row codec compatible with Unity's C# and BCL profile.</summary>
    public static string EmitUnity(GaProgram program, string className = "GaRowCodec") =>
        Emit(program, className, unityCompatible: true);

    private static string Emit(GaProgram program, string className, bool unityCompatible)
    {
        if (program is null) throw new ArgumentNullException(nameof(program));
        if (className is null) throw new ArgumentNullException(nameof(className));
        if (!SyntaxFacts.IsValidIdentifier(className) || className.StartsWith('@') ||
            className is "SystemId" or "SourceDigest" or "IrDigest" or "ComponentSchemaDigest"
                or "WordsPerRow" or "EventCapacity" or "UsesSnapshot" or "SnapshotSchema" or "UsesCommands" or "UsesDomainOrder" or "ComponentRemovals"
                or "TickResourceType" or "TickResourceWords" or "TickResource" or "PackTickResource"
                or "BufferSchema" or "BufferRowWords" or "Buffer" or "PackBufferRow"
                or "RemovalTable" or "ComponentAdditions" or "AdditionPayloadWords" or "AdditionTable"
                or "EventTypes" or "EventTypeCount" or "EventPayloadWords" or "EventTable"
                or "CreateEventTypes" or "ReductionTypeCount"
                or "CreateQuery" or "Pack" or "Apply" || className.StartsWith("__GaDecodeAddition", StringComparison.Ordinal)
                || className.StartsWith("__GaDecodeEvent", StringComparison.Ordinal))
            throw new ArgumentException("The codec needs a C# class identifier outside its member names.", nameof(className));

        var writes = WrittenFields(program.Body).Distinct().OrderBy(index => index).ToArray();
        return new Emitter(program, writes, unityCompatible).Emit(className);
    }

    internal static IEnumerable<int> WrittenFields(GaStatement statement) => statement switch
    {
        GaStore { Slot: { IsField: true } slot } => [slot.Index],
        GaArrayStore store => Enumerable.Range(store.Field.FirstField, store.Field.Length),
        GaBlock block => block.Statements.SelectMany(WrittenFields),
        GaIf { Else: { } alternative } branch => WrittenFields(branch.Then).Concat(WrittenFields(alternative)),
        GaIf branch => WrittenFields(branch.Then),
        GaLoop loop => WrittenFields(loop.Body).Concat(WrittenFields(loop.Increment)),
        _ => []
    };

    private sealed class Emitter(GaProgram program, int[] writes, bool unityCompatible)
    {
        private const string Job = "global::SKECS.DeterministicJob<TInput>";
        private const string ReadJob = "global::SKECS.DeterministicBatchReadJob<TInput>";
        private const string FixedType = "global::SKECS.Numerics.Fixed";
        private const string RemovalType = "global::SKECS.GA.GaComponentRemoval";
        private readonly StringBuilder _code = new();
        private readonly Dictionary<string, int> _components = program.Components.Select((component, index) => (component, index))
            .ToDictionary(item => item.component.Id, item => item.index, StringComparer.Ordinal);
        private readonly string[] _commandComponents = program.RemovalComponents
            .Union(program.AdditionComponents.Select(component => component.Id), StringComparer.Ordinal).ToArray();
        private int _indent;

        internal string Emit(string className)
        {
            Line("// <auto-generated/>");
            Line("#nullable enable");
            string visibility = program.TickResourceType is null && program.BufferType is null && program.ReductionTypeCount == 0
                ? "public" : "internal";
            Line($"{visibility} static class @{className}");
            Open();
            Line($"public const string SystemId = {Literal(program.SystemId)};");
            Line($"public const string SourceDigest = {Literal(program.SourceDigest)};");
            Line($"public const string IrDigest = {Literal(GaIrDigest.Program(program))};");
            Line($"public const string ComponentSchemaDigest = {Literal(GaIrDigest.Schema(program))};");
            Line($"public const int WordsPerRow = {Number(Math.Max(1, program.WordCount))};");
            Line($"public const int EventCapacity = {Number(program.EventCapacity)};");
            Line($"public const bool UsesSnapshot = {(program.UsesSnapshot ? "true" : "false")};");
            string snapshotSchema = program.SnapshotLayout is { } layout ? Literal(layout.Schema) : "null";
            Line($"public const string? SnapshotSchema = {snapshotSchema};");
            string tickResourceType = program.TickResourceType is { } tickType ? Literal(tickType) : "null";
            string tickResourceTypeAnnotation = program.TickResourceType is null ? "string?" : "string";
            Line($"public const {tickResourceTypeAnnotation} TickResourceType = {tickResourceType};");
            Line($"public const int TickResourceWords = {Number(program.TickResourceWords)};");
            if (program.TickResourceType is { } resourceType)
                Line($"public static global::SKECS.GA.GaTickResourceCodec<{resourceType}> TickResource {{ get; }} = new(TickResourceType, TickResourceWords, PackTickResource);");
            string bufferSchema = program.BufferSchema is { } schema ? Literal(schema) : "null";
            string bufferSchemaAnnotation = program.BufferSchema is null ? "string?" : "string";
            Line($"public const {bufferSchemaAnnotation} BufferSchema = {bufferSchema};");
            Line($"public const int BufferRowWords = {Number(program.BufferRowWords)};");
            if (program.BufferType is { } bufferType)
                Line($"public static global::SKECS.GA.GaBufferCodec<{bufferType}> Buffer {{ get; }} = new(BufferSchema, BufferRowWords, PackBufferRow);");
            Line($"public const bool UsesCommands = {(program.UsesCommands ? "true" : "false")};");
            Line($"public const bool UsesDomainOrder = {(program.UsesDomainOrder ? "true" : "false")};");
            if (program.RemovalComponents.Count != 0)
            {
                Line($"private static readonly {RemovalType}[] RemovalTable =");
                Open();
                foreach (var component in program.RemovalComponents)
                    Line($"{RemovalType}.For<{component}>(),");
                Close("};");
            }
            string removals = program.RemovalComponents.Count == 0 ? "default" : "RemovalTable";
            Line($"public static global::System.ReadOnlySpan<{RemovalType}> ComponentRemovals => {removals};");
            Line($"public const int AdditionPayloadWords = {Number(program.AdditionPayloadWords)};");
            if (program.AdditionComponents.Count != 0)
                GaAdditionEmitter.EmitTable(program, "AdditionTable", Line, unityCompatible);
            string additions = program.AdditionComponents.Count == 0 ? "default" : "AdditionTable";
            Line($"public static global::System.ReadOnlySpan<{GaAdditionEmitter.AdditionType}> ComponentAdditions => {additions};");
            Line($"public const int EventPayloadWords = {Number(program.EventPayloadWords)};");
            Line($"public const int EventTypeCount = {Number(program.EventTypes.Count)};");
            Line($"public const int ReductionTypeCount = {Number(program.ReductionTypeCount)};");
            if (program.ReductionTypeCount != 0)
                GaAdditionEmitter.EmitEventTable(program, "CreateEventTypes", Line, unityCompatible);
            else
            {
                if (program.EventTypes.Count != 0)
                    GaAdditionEmitter.EmitEventTable(program, "EventTable", Line, unityCompatible);
                string events = program.EventTypes.Count == 0 ? "default" : "EventTable";
                Line($"public static global::System.ReadOnlySpan<{GaAdditionEmitter.EventType}> EventTypes => {events};");
            }
            Line();
            CreateQuery();
            if (program.TickResourceType is not null)
            {
                Line();
                PackTickResource();
            }
            if (program.BufferType is not null)
            {
                Line();
                PackBufferRow();
            }
            Line();
            Pack();
            Line();
            Apply();
            Close();
            return _code.ToString();
        }

        private void CreateQuery()
        {
            Line("public static global::SKECS.DeterministicQuery CreateQuery() => CreateQuery(null);");
            Line();
            Line("public static global::SKECS.DeterministicQuery CreateQuery(global::SKECS.DeterministicSourceOrder? sourceOrder)");
            Open();
            Line("var query = new global::SKECS.DeterministicQuery();");
            foreach (var component in program.Components)
            {
                var access = component.Access == GaFieldAccess.Read && !_commandComponents.Contains(component.Id)
                    ? "Read" : "ReadWrite";
                string membership = component.Origin == GaComponentOrigin.Query ? $"With<{component.Id}>()." : "";
                Line($"query.{membership}{access}<{component.Id}>();");
            }
            foreach (var component in _commandComponents)
                if (!_components.ContainsKey(component))
                    Line($"query.Write<{component}>();");
            Line("if (sourceOrder is not null) query.OrderBy(sourceOrder);");
            Line("return query;");
            Close();
        }

        private void Pack()
        {
            Line($"public static void Pack<TInput>({ReadJob} job, global::System.Span<uint> destination)");
            Line("    where TInput : unmanaged");
            Open();
            Line("if (destination.Length != checked(job.Count * WordsPerRow))");
            Line("    throw new global::System.ArgumentException(\"The destination must contain exactly one packed row per job row.\", nameof(destination));");
            if (program.WordCount == 0)
            {
                Line("destination.Clear();");
            }
            else
            {
                Line("for (int row = 0; row < job.Count; row++)");
                Open();
                Line("var words = destination.Slice(row * WordsPerRow, WordsPerRow);");
                PackComponents();
                for (int index = 0; index < program.Fields.Count; index++)
                    PackField(index);
                Close();
            }
            Close();
        }

        private void PackComponents()
        {
            var used = ComponentIndexes(Enumerable.Range(0, program.Fields.Count)).ToHashSet();
            for (int index = 0; index < program.Components.Count; index++)
            {
                int presence = program.PresenceOffsets[index];
                if (presence < 0)
                {
                    if (used.Contains(index))
                        ReadComponent(index);
                    continue;
                }

                var component = program.Components[index];
                string output = used.Contains(index) ? $"out var component{Number(index)}" : "out _";
                Line($"words[{Number(presence)}] = job.TryRead<{component.Id}>(row, {output}) ? 1u : 0u;");
            }
        }

        private void PackField(int index)
        {
            var field = program.Fields[index];
            PackScalar(field.Type, Field(index), program.Offsets[index], index);
        }

        private void PackTickResource()
        {
            Line($"private static void PackTickResource(in {program.TickResourceType} input, global::System.Span<uint> words)");
            Open();
            Line("if (words.Length != TickResourceWords)");
            Line("    throw new global::System.ArgumentException(\"The destination must match the tick resource schema.\", nameof(words));");
            for (int i = 0; i < program.TickResourceFields.Count; i++)
            {
                var field = program.TickResourceFields[i];
                string access = field.Path.Length == 0 ? "input" : GaFieldPath.CSharpAccess("input", field.Path);
                PackScalar(field.Type, access, program.TickResourceOffsets[i], i);
            }
            Close();
        }

        private void PackBufferRow()
        {
            Line($"private static void PackBufferRow(in {program.BufferType} input, global::System.Span<uint> words)");
            Open();
            Line("if (words.Length != BufferRowWords)");
            Line("    throw new global::System.ArgumentException(\"The destination must match the buffer row schema.\", nameof(words));");
            for (int i = 0; i < program.BufferFields.Count; i++)
            {
                var field = program.BufferFields[i];
                string access = field.Path.Length == 0 ? "input" : GaFieldPath.CSharpAccess("input", field.Path);
                PackScalar(field.Type, access, program.BufferOffsets[i], i);
            }
            Close();
        }

        private void PackScalar(GaScalar type, string access, int word, int index)
        {
            switch (type)
            {
                case GaScalar.Bool:
                    Line($"words[{Number(word)}] = {access} ? 1u : 0u;");
                    break;
                case GaScalar.Int32 or GaScalar.UInt32:
                    Line($"words[{Number(word)}] = unchecked((uint){access});");
                    break;
                case GaScalar.Fixed:
                    string raw = "raw" + Number(index);
                    Line($"var {raw} = unchecked((ulong){access}.Raw);");
                    Line($"words[{Number(word)}] = unchecked((uint){raw});");
                    Line($"words[{Number(word + 1)}] = (uint)({raw} >> 32);");
                    break;
                default:
                    throw new InvalidOperationException("Unknown GA scalar type.");
            }
        }

        private void Apply()
        {
            Line("/// <summary>Writes the successful leading rows of this job after the caller selects the first fault.</summary>");
            Line($"public static void Apply<TInput>({Job} job, int successfulRows, global::System.ReadOnlySpan<uint> successfulPrefix)");
            Line("    where TInput : unmanaged");
            Open();
            Line("if (successfulRows < 0 || successfulRows > job.Count)");
            Line("    throw new global::System.ArgumentOutOfRangeException(nameof(successfulRows));");
            Line("if (successfulPrefix.Length != checked(successfulRows * WordsPerRow))");
            Line("    throw new global::System.ArgumentException(\"The prefix must contain exactly the successful rows.\", nameof(successfulPrefix));");
            ValidateOutputWords();
            if (writes.Length != 0)
            {
                Line("for (int row = 0; row < successfulRows; row++)");
                Open();
                Line("var words = successfulPrefix.Slice(row * WordsPerRow, WordsPerRow);");
                var components = ComponentIndexes(writes).ToArray();
                foreach (int index in components)
                    ReadComponent(index);
                foreach (int index in writes)
                    ApplyField(index);
                foreach (int index in components)
                    Line($"job.Write(row, component{Number(index)});");
                Close();
            }
            Close();
        }

        private void ValidateOutputWords()
        {
            var invalid = writes.Where(index => program.Fields[index].Type == GaScalar.Bool)
                .Select(index => $"successfulPrefix[offset + {Number(program.Offsets[index])}] > 1u").ToList();
            foreach (int index in Enumerable.Range(0, program.Components.Count))
            {
                int presence = program.PresenceOffsets[index];
                if (presence >= 0)
                {
                    string comparison = program.Components[index].Origin == GaComponentOrigin.Own ? "!=" : ">";
                    invalid.Add($"successfulPrefix[offset + {Number(presence)}] {comparison} 1u");
                }
            }
            if (invalid.Count == 0)
                return;
            Line("for (int offset = 0; offset < successfulPrefix.Length; offset += WordsPerRow)");
            Open();
            Line($"if ({string.Join(" || ", invalid)})");
            Line("    throw new global::System.ArgumentException(\"Invalid presence or boolean word in a successful row.\", nameof(successfulPrefix));");
            Close();
        }

        private void ApplyField(int index)
        {
            var field = program.Fields[index];
            int word = program.Offsets[index];
            string bits = $"words[{Number(word)}]";
            string value = field.Type switch
            {
                GaScalar.Bool => $"{bits} != 0u",
                GaScalar.Int32 => $"unchecked((int){bits})",
                GaScalar.UInt32 => bits,
                GaScalar.Fixed => $"{FixedType}.FromRaw(unchecked((long)({bits} | ((ulong)words[{Number(word + 1)}] << 32))))",
                _ => throw new InvalidOperationException("Unknown GA scalar type.")
            };
            if (field.ClrEnumType != null)
                value = $"({field.ClrEnumType})({value})";
            Line($"{Field(index)} = {value};");
        }

        private IEnumerable<int> ComponentIndexes(IEnumerable<int> fields) =>
            fields.Select(index => _components[program.Fields[index].Component]).Distinct().OrderBy(index => index);

        private void ReadComponent(int index) =>
            Line($"var component{Number(index)} = job.Read<{program.Components[index].Id}>(row);");

        private string Field(int index)
        {
            var field = program.Fields[index];
            return GaFieldPath.CSharpAccess("component" + Number(_components[field.Component]), field.Path);
        }

        private void Open()
        {
            Line("{");
            _indent++;
        }

        private void Close(string text = "}")
        {
            _indent--;
            Line(text);
        }

        private void Line(string text = "")
        {
            if (text.Length != 0)
                _code.Append(' ', _indent * 4).Append(text);
            _code.Append('\n');
        }

        private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
    }
}
