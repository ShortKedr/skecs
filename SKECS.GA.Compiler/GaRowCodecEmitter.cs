using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SKECS.GA;

/// <summary>Emits typed packing and writeback for the canonical rows of a deterministic job.</summary>
public static class GaRowCodecEmitter
{
    public static string Emit(GaProgram program, string className = "GaRowCodec")
    {
        ArgumentNullException.ThrowIfNull(program);
        ArgumentNullException.ThrowIfNull(className);
        if (!SyntaxFacts.IsValidIdentifier(className) || className.StartsWith('@') ||
            className is "SystemId" or "SourceDigest" or "IrDigest" or "ComponentSchemaDigest"
                or "WordsPerRow" or "CreateQuery" or "Pack" or "Apply")
            throw new ArgumentException("The codec needs a C# class identifier outside its member names.", nameof(className));

        var writes = WrittenFields(program.Body).Distinct().Order().ToArray();
        return new Emitter(program, writes).Emit(className);
    }

    private static IEnumerable<int> WrittenFields(GaStatement statement) => statement switch
    {
        GaStore { Slot: { IsField: true } slot } => [slot.Index],
        GaBlock block => block.Statements.SelectMany(WrittenFields),
        GaIf { Else: { } alternative } branch => WrittenFields(branch.Then).Concat(WrittenFields(alternative)),
        GaIf branch => WrittenFields(branch.Then),
        GaLoop loop => WrittenFields(loop.Body).Concat(WrittenFields(loop.Increment)),
        _ => []
    };

    private sealed class Emitter(GaProgram program, int[] writes)
    {
        private const string Job = "global::SKECS.DeterministicJob<TInput>";
        private const string ReadJob = "global::SKECS.DeterministicBatchReadJob<TInput>";
        private const string FixedType = "global::SKECS.Numerics.Fixed";
        private readonly StringBuilder _code = new();
        private readonly Dictionary<string, int> _components = program.Components.Select((component, index) => (component, index))
            .ToDictionary(item => item.component.Id, item => item.index, StringComparer.Ordinal);
        private int _indent;

        internal string Emit(string className)
        {
            Line("// <auto-generated/>");
            Line($"public static class @{className}");
            Open();
            Line($"public const string SystemId = {Literal(program.SystemId)};");
            Line($"public const string SourceDigest = {Literal(program.SourceDigest)};");
            Line($"public const string IrDigest = {Literal(GaIrDigest.Program(program))};");
            Line($"public const string ComponentSchemaDigest = {Literal(GaIrDigest.Schema(program))};");
            Line($"public const int WordsPerRow = {Number(program.WordCount)};");
            Line();
            CreateQuery();
            Line();
            Pack();
            Line();
            Apply();
            Close();
            return _code.ToString();
        }

        private void CreateQuery()
        {
            Line("public static global::SKECS.DeterministicQuery CreateQuery()");
            Open();
            Line("var query = new global::SKECS.DeterministicQuery();");
            foreach (var component in program.Components)
            {
                var access = component.Access == GaFieldAccess.Read ? "Read" : "ReadWrite";
                Line($"query.With<{component.Id}>().{access}<{component.Id}>();");
            }
            Line("return query;");
            Close();
        }

        private void Pack()
        {
            Line($"public static void Pack<TInput>({ReadJob} job, global::System.Span<uint> destination)");
            Line("    where TInput : unmanaged");
            Open();
            Line("if (destination.Length != checked(job.Count * WordsPerRow))");
            Line("    throw new global::System.ArgumentException(\"The destination must contain exactly one packed row per job row.\", nameof(destination));");
            if (program.Fields.Count != 0)
            {
                Line("for (int row = 0; row < job.Count; row++)");
                Open();
                Line("var words = destination.Slice(row * WordsPerRow, WordsPerRow);");
                foreach (int index in ComponentIndexes(Enumerable.Range(0, program.Fields.Count)))
                    ReadComponent(index);
                for (int index = 0; index < program.Fields.Count; index++)
                    PackField(index);
                Close();
            }
            Close();
        }

        private void PackField(int index)
        {
            var field = program.Fields[index];
            string access = Field(index);
            int word = program.Offsets[index];
            switch (field.Type)
            {
                case GaScalar.Bool:
                    Line($"words[{Number(word)}] = {access} ? 1u : 0u;");
                    break;
                case GaScalar.Int32 or GaScalar.UInt32:
                    Line($"words[{Number(word)}] = unchecked((uint){access});");
                    break;
                case GaScalar.Fixed:
                    string raw = "raw" + Number(index);
                    Line($"var {raw} = unchecked((ulong){access}.Raw);");
                    Line($"words[{Number(word)}] = unchecked((uint){raw});");
                    Line($"words[{Number(word + 1)}] = (uint)({raw} >> 32);");
                    break;
                default:
                    throw new InvalidOperationException("Unknown GA scalar type.");
            }
        }

        private void Apply()
        {
            Line("/// <summary>Writes the successful leading rows of this job after the caller selects the first fault.</summary>");
            Line($"public static void Apply<TInput>({Job} job, int successfulRows, global::System.ReadOnlySpan<uint> successfulPrefix)");
            Line("    where TInput : unmanaged");
            Open();
            Line("if (successfulRows < 0 || successfulRows > job.Count)");
            Line("    throw new global::System.ArgumentOutOfRangeException(nameof(successfulRows));");
            Line("if (successfulPrefix.Length != checked(successfulRows * WordsPerRow))");
            Line("    throw new global::System.ArgumentException(\"The prefix must contain exactly the successful rows.\", nameof(successfulPrefix));");
            if (writes.Length != 0)
            {
                ValidateBooleans();
                Line("for (int row = 0; row < successfulRows; row++)");
                Open();
                Line("var words = successfulPrefix.Slice(row * WordsPerRow, WordsPerRow);");
                var components = ComponentIndexes(writes).ToArray();
                foreach (int index in components)
                    ReadComponent(index);
                foreach (int index in writes)
                    ApplyField(index);
                foreach (int index in components)
                    Line($"job.Write(row, component{Number(index)});");
                Close();
            }
            Close();
        }

        private void ValidateBooleans()
        {
            var offsets = writes.Where(index => program.Fields[index].Type == GaScalar.Bool)
                .Select(index => program.Offsets[index]).ToArray();
            if (offsets.Length == 0)
                return;
            Line("for (int offset = 0; offset < successfulPrefix.Length; offset += WordsPerRow)");
            Open();
            string invalid = string.Join(" || ", offsets.Select(offset => $"successfulPrefix[offset + {Number(offset)}] > 1u"));
            Line($"if ({invalid})");
            Line("    throw new global::System.ArgumentException(\"A writable boolean must be encoded as 0 or 1.\", nameof(successfulPrefix));");
            Close();
        }

        private void ApplyField(int index)
        {
            var field = program.Fields[index];
            int word = program.Offsets[index];
            string bits = $"words[{Number(word)}]";
            string value = field.Type switch
            {
                GaScalar.Bool => $"{bits} != 0u",
                GaScalar.Int32 => $"unchecked((int){bits})",
                GaScalar.UInt32 => bits,
                GaScalar.Fixed => $"{FixedType}.FromRaw(unchecked((long)({bits} | ((ulong)words[{Number(word + 1)}] << 32))))",
                _ => throw new InvalidOperationException("Unknown GA scalar type.")
            };
            if (field.ClrEnumType != null)
                value = $"({field.ClrEnumType})({value})";
            Line($"{Field(index)} = {value};");
        }

        private IEnumerable<int> ComponentIndexes(IEnumerable<int> fields) =>
            fields.Select(index => _components[program.Fields[index].Component]).Distinct().Order();

        private void ReadComponent(int index) =>
            Line($"var component{Number(index)} = job.Read<{program.Components[index].Id}>(row);");

        private string Field(int index)
        {
            var field = program.Fields[index];
            return "component" + Number(_components[field.Component]) + "." +
                string.Join(".", field.Path.Split('.').Select(segment => "@" + segment));
        }

        private void Open()
        {
            Line("{");
            _indent++;
        }

        private void Close()
        {
            _indent--;
            Line("}");
        }

        private void Line(string text = "")
        {
            if (text.Length != 0)
                _code.Append(' ', _indent * 4).Append(text);
            _code.Append('\n');
        }

        private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
    }
}
