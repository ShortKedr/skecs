using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SKECS.GA;

/// <summary>Emits an ordinary C# processor for the shared deterministic runner.</summary>
public static class GaCpuAdapterEmitter
{
    /// <summary>Emits a public adapter with a generic Register method for the given GA program.</summary>
    public static string Emit(GaProgram program, string className = "GaCpuAdapter")
    {
        ArgumentNullException.ThrowIfNull(program);
        ArgumentNullException.ThrowIfNull(className);
        if (!SyntaxFacts.IsValidIdentifier(className) || className.StartsWith('@') ||
            className == "Register" || className.StartsWith("__Ga", StringComparison.Ordinal))
            throw new ArgumentException("The adapter needs a C# class identifier outside its member names.", nameof(className));

        return new Emitter(program).Emit(className);
    }

    private sealed class Emitter(GaProgram program)
    {
        private const string FixedType = "global::SKECS.Numerics.Fixed";
        private readonly StringBuilder _code = new();
        private readonly Dictionary<string, int> _components = program.Components.Select((component, index) => (component, index))
            .ToDictionary(item => item.component.Id, item => item.index, StringComparer.Ordinal);
        private readonly HashSet<int> _writable = new();
        private readonly List<GaSourceSpan> _sources = new();
        private readonly Dictionary<string, FaultHelper> _helpers = new(StringComparer.Ordinal);
        private int _loop;
        private int _indent;

        internal string Emit(string className)
        {
            // Emit the row body first to find the exact field writes and fault paths it uses.
            _indent = 5;
            Statement(program.Body);
            var body = _code.ToString();
            _code.Clear();
            _indent = 0;

            Line("// <auto-generated/>");
            Line("#pragma warning disable CS0162, CS0219");
            Line($"public static class @{className}");
            Open();
            Register();
            Processor(body);
            if (_sources.Count != 0)
                FaultInfrastructure();
            Close();
            return _code.ToString();
        }

        private void Register()
        {
            Line("public static global::SKECS.DeterministicWorkload<TInput> Register<TInput>(");
            Line("    global::SKECS.DeterministicWorkload<TInput> workload, global::SKECS.SystemStage stage)");
            Line("    where TInput : unmanaged");
            Open();
            Line("global::System.ArgumentNullException.ThrowIfNull(workload);");
            Line("var query = new global::SKECS.DeterministicQuery();");
            foreach (var component in program.Components)
            {
                var access = component.Access == GaFieldAccess.Read ? "Read" : "ReadWrite";
                Line($"query.With<{component.Id}>().{access}<{component.Id}>();");
            }
            Line("return workload.AddSystem(stage, query, new __GaProcessor<TInput>());");
            Close();
            Line();
        }

        private void Processor(string body)
        {
            Line("private readonly struct __GaProcessor<TInput> : global::SKECS.IDeterministicJobProcessor<TInput>");
            Line("    where TInput : unmanaged");
            Open();
            Line("public void Execute(global::SKECS.DeterministicJob<TInput> job)");
            Open();
            Line("unchecked");
            Open();
            Line("for (int row = 0; row < job.Count; row++)");
            Open();
            foreach (var index in program.Fields.Select(field => _components[field.Component]).Distinct().Order())
                Line($"var component{Number(index)} = job.Read<{program.Components[index].Id}>(row);");
            for (int index = 0; index < program.Locals.Count; index++)
                Line($"{Scalar(program.Locals[index])} local{Number(index)} = default;");
            if (_sources.Count != 0)
                Line("var faults = new __GaFaultState<TInput>(job, row);");
            _code.Append(body);
            foreach (int index in _writable.Order())
                Line($"job.Write(row, component{Number(index)});");
            Close();
            Close();
            Close();
            Close();
        }

        private void Statement(GaStatement statement)
        {
            switch (statement)
            {
                case GaBlock block:
                    foreach (var item in block.Statements)
                        Statement(item);
                    break;
                case GaStore store:
                    string expression = Expression(store.Value);
                    if (store.Slot.IsField)
                    {
                        var field = program.Fields[store.Slot.Index];
                        _writable.Add(_components[field.Component]);
                        if (field.ClrEnumType != null)
                            expression = $"({field.ClrEnumType})({expression})";
                    }
                    Line($"{Slot(store.Slot)} = {expression};");
                    break;
                case GaIf branch:
                    Line($"if ({Expression(branch.Condition)})");
                    Open();
                    Statement(branch.Then);
                    Close();
                    if (branch.Else != null)
                    {
                        Line("else");
                        Open();
                        Statement(branch.Else);
                        Close();
                    }
                    break;
                case GaLoop loop:
                    string counter = "iteration" + Number(_loop++);
                    Line($"for (int {counter} = 0; {Expression(loop.Condition)}; {counter}++)");
                    Open();
                    Line($"if ({counter} == {Number(loop.MaximumIterations)})");
                    Line($"    throw faults.Exception(global::SKECS.GA.GaFaultKind.IterationLimit, faults.EvaluationOrdinal, {Site(loop.Condition.Source)});");
                    Statement(loop.Body);
                    Statement(loop.Increment);
                    Close();
                    break;
                default:
                    throw new InvalidOperationException("Unknown GA IR statement.");
            }
        }

        private string Expression(GaValue value) => value switch
        {
            GaConstant constant => Constant(constant),
            GaLoad load => Load(load.Slot),
            GaCast cast => Convert(cast),
            GaUnary unary => Unary(unary),
            GaBinary binary => Binary(binary),
            GaSelect select => $"({Expression(select.Condition)} ? {Expression(select.True)} : {Expression(select.False)})",
            _ => throw new InvalidOperationException("Unknown GA IR value.")
        };

        private string Convert(GaCast cast)
        {
            string operand = Expression(cast.Operand);
            if (cast.Operand.Type == cast.Type)
                return operand;
            if (cast.Type == GaScalar.Fixed)
                return $"{FixedType}.FromInt32({operand})";
            if (cast.Operand.Type == GaScalar.Fixed)
                return $"(int)({operand})";
            string target = Scalar(cast.Type);
            if (!cast.Checked)
                return $"({target})({operand})";

            string test = cast.Type == GaScalar.Int32 ? "value > int.MaxValue" : "value < 0";
            return FaultCall("Cast" + cast.Type, target, $"{Scalar(cast.Operand.Type)} value", operand,
                [$"if ({test})", "    throw faults.Exception(global::SKECS.GA.GaFaultKind.Overflow, ordinal, site);",
                    $"return ({target})value;"], cast.Source);
        }

        private string Unary(GaUnary unary)
        {
            string operand = Expression(unary.Operand);
            if (unary.Type == GaScalar.Fixed)
                return FixedFaultCall("NegateFixed", $"{FixedType} value", operand, "-value", unary.Source);
            if (unary.Checked)
            {
                return FaultCall("NegateInt32", "int", "int value", operand,
                    ["if (value == int.MinValue)", "    throw faults.Exception(global::SKECS.GA.GaFaultKind.Overflow, ordinal, site);",
                        "return -value;"], unary.Source);
            }
            var op = unary.Operator switch
            {
                GaUnaryOperator.Negate => "-",
                GaUnaryOperator.BitwiseNot => "~",
                GaUnaryOperator.Not => "!",
                _ => throw new InvalidOperationException("Unknown GA unary operator.")
            };
            return $"({op}({operand}))";
        }

        private string Binary(GaBinary binary)
        {
            var op = BinaryToken(binary.Operator);
            var left = Expression(binary.Left);
            var right = Expression(binary.Right);
            string args = $"{left}, {right}";
            string type = Scalar(binary.Left.Type);
            string names = $"{type} left, {type} right";
            string helper = binary.Operator.ToString() + binary.Left.Type;
            const string overflow = "    throw faults.Exception(global::SKECS.GA.GaFaultKind.Overflow, ordinal, site);";

            if (binary.Left.Type == GaScalar.Fixed)
                return binary.Type == GaScalar.Fixed
                    ? FixedFaultCall(helper, names, args, $"left {op} right", binary.Source)
                    : $"({left} {op} {right})";

            if (binary.Operator is GaBinaryOperator.Divide or GaBinaryOperator.Remainder)
            {
                var lines = new List<string>
                {
                    "if (right == 0)",
                    "    throw faults.Exception(global::SKECS.GA.GaFaultKind.DivideByZero, ordinal, site);"
                };
                if (binary.Left.Type == GaScalar.Int32)
                {
                    lines.Add("if (left == int.MinValue && right == -1)");
                    lines.Add(overflow);
                }
                lines.Add($"return left {op} right;");
                return FaultCall(helper, type, names, args, lines, binary.Source);
            }
            if (binary.Checked)
            {
                bool signed = binary.Left.Type == GaScalar.Int32;
                string wide = signed ? "long" : "ulong";
                string test = signed ? "value < int.MinValue || value > int.MaxValue" : "value > uint.MaxValue";
                return FaultCall(helper, type, names, args,
                    [$"{wide} value = unchecked(({wide})left {op} right);", $"if ({test})", overflow,
                        $"return ({type})value;"], binary.Source);
            }
            return $"({left} {op} {right})";
        }

        private string Site(GaSourceSpan source)
        {
            int index = _sources.Count;
            _sources.Add(source);
            return Number(index);
        }

        private string FaultCall(string name, string type, string parameters, string arguments, IReadOnlyList<string> lines,
            GaSourceSpan source)
        {
            _helpers.TryAdd(name, new FaultHelper(type, parameters, lines));
            return $"__Ga{name}({arguments}, ref faults, {Site(source)})";
        }

        private string FixedFaultCall(string name, string parameters, string arguments, string calculation, GaSourceSpan source)
        {
            return FaultCall(name, FixedType, parameters, arguments,
                ["try", "{", $"    return {calculation};", "}",
                    "catch (global::System.ArithmeticException error) when (error is global::System.OverflowException or global::System.DivideByZeroException)",
                    "{", "    var kind = error is global::System.OverflowException",
                    "        ? global::SKECS.GA.GaFaultKind.Overflow : global::SKECS.GA.GaFaultKind.DivideByZero;",
                    "    throw faults.Exception(kind, ordinal, site);", "}"], source);
        }

        private void FaultInfrastructure()
        {
            Line();
            Line("private static readonly global::SKECS.GA.GaSourceSpan[] __GaSources = new global::SKECS.GA.GaSourceSpan[]");
            Open();
            foreach (var source in _sources)
                Line($"new global::SKECS.GA.GaSourceSpan({Literal(source.File)}, {Number(source.Start)}, {Number(source.Length)}),");
            Close("};");
            Line();
            Line("private ref struct __GaFaultState<TInput> where TInput : unmanaged");
            Open();
            Line("private readonly global::SKECS.DeterministicJob<TInput> job;");
            Line("private readonly int row;");
            Line("internal ulong EvaluationOrdinal;");
            Line();
            Line("internal __GaFaultState(global::SKECS.DeterministicJob<TInput> job, int row)");
            Open();
            Line("this.job = job;");
            Line("this.row = row;");
            Line("EvaluationOrdinal = 0ul;");
            Close();
            Line();
            Line("internal global::SKECS.GA.GaExecutionException Exception(global::SKECS.GA.GaFaultKind kind, ulong ordinal, int site)");
            Open();
            Line("var entity = job.GetEntity(row);");
            Line("long sourceOrdinal = (long)job.JobId * global::SKECS.DeterministicRunner<TInput>.LogicalJobSize + row;");
            Line($"return new global::SKECS.GA.GaExecutionException({Literal(program.SystemId)}, job.TickIndex, sourceOrdinal,");
            Line("    entity.Id, entity.Version, new global::SKECS.GA.GaKernelFault(kind, ordinal, __GaSources[site]));");
            Close();
            Close();

            foreach (var (name, helper) in _helpers)
            {
                Line();
                Line($"private static {helper.Type} __Ga{name}<TInput>({helper.Parameters}, ref __GaFaultState<TInput> faults, int site)");
                Line("    where TInput : unmanaged");
                Open();
                Line("ulong ordinal = unchecked(faults.EvaluationOrdinal++);");
                foreach (var code in helper.Lines)
                    Line(code);
                Close();
            }
        }

        private string Load(GaSlot slot)
        {
            string access = Slot(slot);
            return slot.IsField && program.Fields[slot.Index].ClrEnumType != null ? $"({Scalar(slot.Type)}){access}" : access;
        }

        private string Slot(GaSlot slot)
        {
            if (!slot.IsField)
                return "local" + Number(slot.Index);
            var field = program.Fields[slot.Index];
            return "component" + Number(_components[field.Component]) + "." +
                string.Join(".", field.Path.Split('.').Select(segment => "@" + segment));
        }

        private static string Constant(GaConstant constant) => constant.Type switch
        {
            GaScalar.Bool => constant.Bits == 0 ? "false" : "true",
            GaScalar.Int32 => $"unchecked((int)0x{unchecked((uint)constant.Bits).ToString("x8", CultureInfo.InvariantCulture)}u)",
            GaScalar.UInt32 => unchecked((uint)constant.Bits).ToString(CultureInfo.InvariantCulture) + "u",
            GaScalar.Fixed => $"{FixedType}.FromRaw(unchecked((long)0x{constant.Bits.ToString("x16", CultureInfo.InvariantCulture)}ul))",
            _ => throw new InvalidOperationException("Unknown GA scalar type.")
        };

        private static string Scalar(GaScalar type) => type switch
        {
            GaScalar.Bool => "bool",
            GaScalar.Int32 => "int",
            GaScalar.UInt32 => "uint",
            GaScalar.Fixed => FixedType,
            _ => throw new InvalidOperationException("Unknown GA scalar type.")
        };

        private static string BinaryToken(GaBinaryOperator op) => op switch
        {
            GaBinaryOperator.Add => "+",
            GaBinaryOperator.Subtract => "-",
            GaBinaryOperator.Multiply => "*",
            GaBinaryOperator.Divide => "/",
            GaBinaryOperator.Remainder => "%",
            GaBinaryOperator.BitwiseAnd => "&",
            GaBinaryOperator.BitwiseOr => "|",
            GaBinaryOperator.ExclusiveOr => "^",
            GaBinaryOperator.LeftShift => "<<",
            GaBinaryOperator.RightShift => ">>",
            GaBinaryOperator.UnsignedRightShift => ">>>",
            GaBinaryOperator.Equal => "==",
            GaBinaryOperator.NotEqual => "!=",
            GaBinaryOperator.Less => "<",
            GaBinaryOperator.LessOrEqual => "<=",
            GaBinaryOperator.Greater => ">",
            GaBinaryOperator.GreaterOrEqual => ">=",
            GaBinaryOperator.AndAlso => "&&",
            GaBinaryOperator.OrElse => "||",
            _ => throw new InvalidOperationException("Unknown GA binary operator.")
        };

        private void Open()
        {
            Line("{");
            _indent++;
        }

        private void Close(string text = "}")
        {
            _indent--;
            Line(text);
        }

        private void Line(string text = "")
        {
            if (text.Length != 0)
                _code.Append(' ', _indent * 4).Append(text);
            _code.Append('\n');
        }

        private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
        private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

        private sealed record FaultHelper(string Type, string Parameters, IReadOnlyList<string> Lines);
    }
}
