using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SKECS.GA;

/// <summary>Emits an ordinary C# processor for the shared deterministic runner.</summary>
public static class GaCpuAdapterEmitter
{
    /// <summary>Emits an adapter with a Register method for the given GA program.</summary>
    public static string Emit(GaProgram program, string className = "GaCpuAdapter")
    {
        ArgumentNullException.ThrowIfNull(program);
        ArgumentNullException.ThrowIfNull(className);
        if (!SyntaxFacts.IsValidIdentifier(className) || className.StartsWith('@') ||
            className == "Register" || className.StartsWith("__Ga", StringComparison.Ordinal))
            throw new ArgumentException("The adapter needs a C# class identifier outside its member names.", nameof(className));

        return new Emitter(program).Emit(className);
    }

    private sealed class Emitter(GaProgram program)
    {
        private const string FixedType = "global::SKECS.Numerics.Fixed";
        private const string OutputType = "global::SKECS.GA.GaOutputRecord";
        private const string RemovalType = "global::SKECS.GA.GaComponentRemoval";
        private readonly StringBuilder _code = new();
        private readonly Dictionary<string, int> _components = program.Components.Select((component, index) => (component, index))
            .ToDictionary(item => item.component.Id, item => item.index, StringComparer.Ordinal);
        private readonly string[] _commandComponents = program.RemovalComponents
            .Union(program.AdditionComponents.Select(component => component.Id), StringComparer.Ordinal).ToArray();
        private readonly HashSet<int> _writable = new();
        private readonly List<GaSourceSpan> _sources = new();
        private readonly Dictionary<string, FaultHelper> _helpers = new(StringComparer.Ordinal);
        private readonly List<GaTryRead> _optionalReads = new();
        private readonly List<GaBlockValue> _blockValues = new();
        private string _faultState = "faults";
        private int _loop;
        private int _arrayStore;
        private int _indent;
        private string InputType => program.TickResourceType ?? "TInput";
        private string TypeParameters => program.TickResourceType is null ? "<TInput>" : "";
        private string InputConstraint => program.TickResourceType is null ? " where TInput : unmanaged" : "";
        private bool UsesBuffer => program.BufferSchema is not null;
        private bool UsesBatch => UsesBuffer || program.UsesSnapshot;
        private bool BindsReductions => program.ReductionTypeCount != 0;
        private string ReductionBindings => BindsReductions ? $", {GaAdditionEmitter.EventType}[] __GaEvents" : "";
        private bool PackedOutputs => program.AdditionComponents.Count != 0 || program.EventTypes.Count != 0 || program.UsesDomainOrder;
        private int OutputWidth => checked(GaOutputRecord.Words + program.OutputPayloadWords +
            (program.UsesDomainOrder ? GaOutputRecord.DomainWordCount : 0));

        internal string Emit(string className)
        {
            // Emit the row body first to find the exact field writes and fault paths it uses.
            _indent = UsesBatch || BindsReductions ? 4 : 5;
            Statement(program.Body);
            for (int index = 0; index < _blockValues.Count; index++)
                EmitBlockValue(index, _blockValues[index]);
            var body = _code.ToString();
            _code.Clear();
            _indent = 0;

            Line("// <auto-generated/>");
            Line("#nullable enable");
            Line("#pragma warning disable CS0162, CS0219");
            string visibility = program.TickResourceType is null && !BindsReductions ? "public" : "internal";
            Line($"{visibility} static class @{className}");
            Open();
            if (program.RemovalComponents.Count != 0)
            {
                Line($"private static readonly {RemovalType}[] __GaRemovals =");
                Open();
                foreach (var component in program.RemovalComponents)
                    Line($"{RemovalType}.For<{component}>(),");
                Close("};");
                Line();
            }
            if (program.AdditionComponents.Count != 0)
            {
                GaAdditionEmitter.EmitTable(program, "__GaAdditions", Line);
                Line();
            }
            if (program.EventTypes.Count != 0)
            {
                GaAdditionEmitter.EmitEventTable(program, BindsReductions ? "__GaCreateEvents" : "__GaEvents", Line);
                Line();
            }
            Register(grouped: false);
            Register(grouped: true);
            CreateQuery();
            Processor(body);
            for (int index = 0; index < _optionalReads.Count; index++)
                EmitOptionalRead(index, _optionalReads[index]);
            if (_sources.Count != 0 || _blockValues.Count != 0)
                FaultInfrastructure();
            Close();
            return _code.ToString();
        }

        private void Register(bool grouped)
        {
            string owner = grouped ? "group" : "workload";
            string ownerType = grouped ? $"global::SKECS.DeterministicCommitGroup<{InputType}>"
                : $"global::SKECS.DeterministicWorkload<{InputType}>";
            string parameters = $"{ownerType} {owner}" + (grouped ? "" : ", global::SKECS.SystemStage stage");
            string arguments = owner + (grouped ? "" : ", stage");
            if (UsesBuffer)
            {
                parameters += ", global::SKECS.GA.GaTickBuffer buffer";
                arguments += ", buffer";
            }
            if (program.UsesSnapshot)
            {
                parameters += ", global::SKECS.GA.GaTickSnapshot snapshot";
                arguments += ", snapshot";
            }
            if (BindsReductions)
            {
                parameters += $", {GaAdditionEmitter.ReductionParameters(program)}";
                arguments += $", {GaAdditionEmitter.ReductionArguments(program)}";
            }
            Line($"public static {ownerType} Register{TypeParameters}({parameters})");
            Line($"   {InputConstraint} => Register({arguments}, null);");
            Line();
            Line($"public static {ownerType} Register{TypeParameters}(");
            Line($"    {parameters},");
            Line("    global::SKECS.DeterministicSourceOrder? sourceOrder)");
            if (program.TickResourceType is null)
                Line("    where TInput : unmanaged");
            Open();
            Line($"global::System.ArgumentNullException.ThrowIfNull({owner});");
            if (!grouped && program.UsesDomainOrder)
            {
                Line("throw new global::System.InvalidOperationException(\"A GA kernel with domain order requires a keyed commit group.\");");
                Close();
                Line();
                return;
            }
            if (grouped && program.UsesDomainOrder)
            {
                Line("if (group.DomainOrder is null)");
                Line("    throw new global::System.InvalidOperationException(\"A GA kernel with domain order requires a keyed commit group.\");");
            }
            else if (grouped && program.EventCapacity != 0)
            {
                Line("if (group.DomainOrder is not null)");
                Line("    throw new global::System.InvalidOperationException(\"A GA producer with outputs in a keyed commit group must use domain order.\");");
            }
            string stage = grouped ? "" : "stage, ";
            if (BindsReductions)
                Line($"var __GaEvents = __GaCreateEvents({GaAdditionEmitter.ReductionArguments(program)});");
            if (program.BufferSchema is { } bufferSchema)
            {
                string snapshot = program.UsesSnapshot
                    ? program.SnapshotLayout is { } layout ? $", snapshot, {Literal(layout.Schema)}" : ", snapshot"
                    : "";
                string execute = BindsReductions
                    ? $"(job, bufferPacket, snapshotPacket) => __GaExecute{TypeParameters}(job, bufferPacket, snapshotPacket, __GaEvents)"
                    : $"__GaExecute{TypeParameters}";
                Line($"return {owner}.AddBatchSystem({stage}__GaCreateQuery(sourceOrder), new global::SKECS.GA.GaBufferCpuBatch<{InputType}>(buffer, {Literal(bufferSchema)}, {Number(program.BufferRowWords)}, {execute}{snapshot}));");
            }
            else if (program.UsesSnapshot)
            {
                string schema = program.SnapshotLayout is { } layout ? $", {Literal(layout.Schema)}" : "";
                string execute = BindsReductions ? $"(job, packet) => __GaExecute{TypeParameters}(job, packet, __GaEvents)"
                    : $"__GaExecute{TypeParameters}";
                Line($"return {owner}.AddBatchSystem({stage}__GaCreateQuery(sourceOrder), new global::SKECS.GA.GaSnapshotCpuBatch<{InputType}>(snapshot, {execute}{schema}));");
            }
            else if (BindsReductions)
                Line($"return {owner}.AddSystem({stage}__GaCreateQuery(sourceOrder), job => __GaExecute{TypeParameters}(job, __GaEvents));");
            else
                Line($"return {owner}.AddSystem({stage}__GaCreateQuery(sourceOrder), new __GaProcessor{TypeParameters}());");
            Close();
            Line();
        }

        private void CreateQuery()
        {
            Line("private static global::SKECS.DeterministicQuery __GaCreateQuery(global::SKECS.DeterministicSourceOrder? sourceOrder)");
            Open();
            Line("var query = new global::SKECS.DeterministicQuery();");
            foreach (var component in program.Components)
            {
                var access = component.Access == GaFieldAccess.Read && !_commandComponents.Contains(component.Id)
                    ? "Read" : "ReadWrite";
                string membership = component.Origin == GaComponentOrigin.Query ? $"With<{component.Id}>()." : "";
                Line($"query.{membership}{access}<{component.Id}>();");
            }
            foreach (var component in _commandComponents)
                if (!_components.ContainsKey(component))
                    Line($"query.Write<{component}>();");
            Line("if (sourceOrder is not null) query.OrderBy(sourceOrder);");
            Line("return query;");
            Close();
            Line();
        }

        private void Processor(string body)
        {
            if (UsesBuffer)
            {
                Line($"private static void __GaExecute{TypeParameters}(global::SKECS.DeterministicJob<{InputType}> job,");
                Line($"    global::SKECS.GA.GaBufferPacket buffer, global::SKECS.GA.GaSnapshotPacket? snapshot{ReductionBindings}){InputConstraint}");
            }
            else if (program.UsesSnapshot)
            {
                Line($"private static void __GaExecute{TypeParameters}(global::SKECS.DeterministicJob<{InputType}> job,");
                Line($"    global::SKECS.GA.GaSnapshotPacket snapshot{ReductionBindings}){InputConstraint}");
            }
            else if (BindsReductions)
            {
                Line($"private static void __GaExecute{TypeParameters}(global::SKECS.DeterministicJob<{InputType}> job{ReductionBindings}){InputConstraint}");
            }
            else
            {
                Line($"private readonly struct __GaProcessor{TypeParameters} : global::SKECS.IDeterministicJobProcessor<{InputType}>");
                if (program.TickResourceType is null)
                    Line("    where TInput : unmanaged");
                Open();
                Line($"public void Execute(global::SKECS.DeterministicJob<{InputType}> job)");
            }
            Open();
            Line("unchecked");
            Open();
            if (program.TickResourceFields.Count != 0)
                Line("var tickResource = job.Input;");
            if (program.EventCapacity != 0)
            {
                int capacity = PackedOutputs ? checked(program.EventCapacity * OutputWidth) : program.EventCapacity;
                string allocation = capacity <= 128 ? "stackalloc" : "new";
                string elementType = PackedOutputs ? "uint" : program.UsesCommands ? OutputType : "int";
                Line($"global::System.Span<{elementType}> stagedEvents = {allocation} {elementType}[{Number(capacity)}];");
            }
            Line("for (int row = 0; row < job.Count; row++)");
            Open();
            if (program.EventCapacity != 0)
                Line("int eventCount = 0;");
            if (program.UsesDomainOrder)
            {
                Line("bool hasDomainOrder = false;");
                Line("int domainPrimary = 0, domainSecondary = 0;");
            }
            if (_sources.Count != 0 || _blockValues.Count != 0 ||
                program.Components.Any(component => component.Origin == GaComponentOrigin.Own))
                Line($"var faults = new __GaFaultState<{InputType}>(job, row);");
            LoadComponents();
            for (int index = 0; index < program.Locals.Count; index++)
                Line($"{Scalar(program.Locals[index])} local{Number(index)} = default;");
            for (int index = 0; index < program.TicketLocalCount; index++)
                Line($"int ticket{Number(index)} = -1;");
            _code.Append(body);
            foreach (int index in _writable.Order())
                Line($"job.Write(row, component{Number(index)});");
            if (program.EventCapacity != 0)
            {
                Line("var eventSource = job.ForEntity(row);");
                if (PackedOutputs)
                {
                    string removals = program.RemovalComponents.Count == 0 ? "default" : "__GaRemovals";
                    string additions = program.AdditionComponents.Count == 0 ? "default" : "__GaAdditions";
                    string width = Number(OutputWidth);
                    string outputFormat = program.EventTypes.Count != 0
                        ? $", {(program.UsesDomainOrder ? "true" : "false")}, __GaEvents"
                        : program.UsesDomainOrder ? ", usesDomainOrder: true" : "";
                    Line($"{OutputType}.ApplyPackedSource(eventSource, stagedEvents[..(eventCount * {width})], {width}, {removals}, {additions}{outputFormat});");
                }
                else if (program.UsesCommands)
                {
                    string removals = program.RemovalComponents.Count == 0 ? "default" : "__GaRemovals";
                    Line($"{OutputType}.ApplySource(eventSource, stagedEvents[..eventCount], {removals});");
                }
                else
                {
                    Line("for (int i = 0; i < eventCount; i++)");
                    Line("    eventSource.Emit(stagedEvents[i]);");
                }
            }
            Close();
            Close();
            Close();
            if (!UsesBatch && !BindsReductions)
                Close();
        }

        private void LoadComponents()
        {
            var used = program.Fields.Select(field => _components[field.Component]).ToHashSet();
            for (int index = 0; index < program.Components.Count; index++)
            {
                var component = program.Components[index];
                string name = "component" + Number(index);
                if (component.Origin == GaComponentOrigin.Query)
                {
                    if (used.Contains(index))
                        Line($"var {name} = job.Read<{component.Id}>(row);");
                    continue;
                }

                string value = used.Contains(index) ? $"out var {name}" : "out _";
                string read = $"job.TryRead<{component.Id}>(row, {value})";
                if (component.Origin == GaComponentOrigin.Optional)
                {
                    Line($"bool {Presence(index)} = {read};");
                }
                else
                {
                    Line($"if (!{read})");
                    Line($"    throw faults.Exception(global::SKECS.GA.GaFaultKind.MissingOwnComponent, 0ul, {Site(component.OwnSource)});");
                }
            }
        }

        private void Statement(GaStatement statement)
        {
            switch (statement)
            {
                case GaBlock block:
                    foreach (var item in block.Statements)
                        Statement(item);
                    break;
                case GaStore store:
                    string expression = Expression(store.Value);
                    if (store.Slot.IsField)
                    {
                        var field = program.Fields[store.Slot.Index];
                        _writable.Add(_components[field.Component]);
                        if (field.ClrEnumType != null)
                            expression = $"({field.ClrEnumType})({expression})";
                    }
                    Line($"{Slot(store.Slot)} = {expression};");
                    break;
                case GaArrayStore store:
                    ArrayStore(store);
                    break;
                case GaEmit emission:
                    if (program.EventCapacity != 0)
                    {
                        string value = Expression(emission.Value);
                        if (program.UsesCommands || PackedOutputs)
                            value = $"{OutputType}.EmitInt32({value})";
                        StageOutput(value);
                    }
                    break;
                case GaEmitTyped emission:
                    if (program.EventCapacity != 0)
                    {
                        var outputType = program.EventTypes[emission.EventTypeIndex];
                        string emit = outputType.IsContribution ? "Contribute" : "EmitTyped";
                        StagePayload(outputType.Offsets, emission.Values, $"{OutputType}.{emit}({Number(emission.EventTypeIndex)})");
                    }
                    break;
                case GaDestroy destroy:
                    if (program.EventCapacity != 0)
                        StageOutput($"{OutputType}.DestroyEntity({Expression(destroy.EntityId)}, {Expression(destroy.Generation)})");
                    break;
                case GaCreate create:
                    if (program.EventCapacity != 0)
                    {
                        if (create.TicketSlot >= 0)
                            Line($"ticket{Number(create.TicketSlot)} = eventCount;");
                        StageOutput($"{OutputType}.CreateEntity()");
                    }
                    break;
                case GaDestroyTicket destroy:
                    if (program.EventCapacity != 0)
                        StageOutput($"{OutputType}.DestroyTicket(ticket{Number(destroy.TicketSlot)})");
                    break;
                case GaRemove remove:
                    if (program.EventCapacity != 0)
                        StageOutput($"{OutputType}.RemoveEntity({Number(remove.ComponentIndex)}, {Expression(remove.EntityId)}, {Expression(remove.Generation)})");
                    break;
                case GaRemoveTicket remove:
                    if (program.EventCapacity != 0)
                        StageOutput($"{OutputType}.RemoveTicket({Number(remove.ComponentIndex)}, ticket{Number(remove.TicketSlot)})");
                    break;
                case GaAdd add:
                    if (program.EventCapacity != 0)
                        StagePayload(program.AdditionComponents[add.ComponentIndex].Offsets, add.Values,
                            $"{OutputType}.AddEntity({Number(add.ComponentIndex)}, {Expression(add.EntityId)}, {Expression(add.Generation)})");
                    break;
                case GaAddTicket add:
                    if (program.EventCapacity != 0)
                        StagePayload(program.AdditionComponents[add.ComponentIndex].Offsets, add.Values,
                            $"{OutputType}.AddTicket({Number(add.ComponentIndex)}, ticket{Number(add.TicketSlot)})");
                    break;
                case GaSetDomainOrder order:
                    Line($"domainPrimary = {Expression(order.Primary)};");
                    Line($"domainSecondary = {Expression(order.Secondary)};");
                    Line("hasDomainOrder = true;");
                    break;
                case GaIf branch:
                    Line($"if ({Expression(branch.Condition)})");
                    Open();
                    Statement(branch.Then);
                    Close();
                    if (branch.Else != null)
                    {
                        Line("else");
                        Open();
                        Statement(branch.Else);
                        Close();
                    }
                    break;
                case GaLoop loop:
                    string counter = "iteration" + Number(_loop++);
                    Line($"for (int {counter} = 0; {Expression(loop.Condition)}; {counter}++)");
                    Open();
                    Line($"if ({counter} == {Number(loop.MaximumIterations)})");
                    Line($"    throw {_faultState}.Exception(global::SKECS.GA.GaFaultKind.IterationLimit, {_faultState}.EvaluationOrdinal, {Site(loop.Condition.Source)});");
                    Statement(loop.Body);
                    Statement(loop.Increment);
                    Close();
                    break;
                default:
                    throw new InvalidOperationException("Unknown GA IR statement.");
            }
        }

        private void ArrayStore(GaArrayStore store)
        {
            var field = program.Fields[store.Field.FirstField];
            _writable.Add(_components[field.Component]);
            string index = "arrayIndex" + Number(_arrayStore++);
            Line($"int {index} = {CheckedArrayIndex(store.Field, store.Index, store.Source)};");
            string access = FieldAccess(field, index);
            if (store.Previous is { } previous)
            {
                string previousValue = field.ClrEnumType is not null ? $"({Scalar(field.Type)}){access}" : access;
                Line($"{Slot(previous)} = {previousValue};");
            }
            string value = Expression(store.Value);
            if (field.ClrEnumType is not null)
                value = $"({field.ClrEnumType})({value})";
            Line($"{access} = {value};");
        }

        private string OutputSlot()
        {
            string width = Number(OutputWidth);
            return $"stagedEvents.Slice(eventCount * {width}, {width})";
        }

        private void StageOutput(string value)
        {
            if (program.UsesDomainOrder)
            {
                Open();
                Line($"var output = {OutputSlot()};");
                Line($"{value}.Write(output);");
                Line($"{OutputType}.WriteDomainOrder(output, hasDomainOrder, domainPrimary, domainSecondary);");
                Close();
            }
            else
                Line(PackedOutputs ? $"{value}.Write({OutputSlot()});" : $"stagedEvents[eventCount] = {value};");
            Line("eventCount++;");
        }

        private void StagePayload(int[] offsets, IReadOnlyList<GaAdditionValue> values, string header)
        {
            Open();
            Line($"var output = {OutputSlot()};");
            Line($"{header}.Write(output);");
            foreach (var value in values)
            {
                int offset = GaOutputRecord.Words + offsets[value.FieldIndex];
                string expression = Expression(value.Value);
                if (value.Value.Type == GaScalar.Fixed)
                {
                    string raw = "additionRaw" + Number(value.FieldIndex);
                    Line($"ulong {raw} = unchecked((ulong)({expression}).Raw);");
                    Line($"output[{Number(offset)}] = unchecked((uint){raw});");
                    Line($"output[{Number(offset + 1)}] = (uint)({raw} >> 32);");
                }
                else
                {
                    string packed = value.Value.Type == GaScalar.Bool ? $"({expression}) ? 1u : 0u" : $"unchecked((uint)({expression}))";
                    Line($"output[{Number(offset)}] = {packed};");
                }
            }
            if (program.UsesDomainOrder)
                Line($"{OutputType}.WriteDomainOrder(output, hasDomainOrder, domainPrimary, domainSecondary);");
            Line("eventCount++;");
            Close();
        }

        private string StoreAndRead(GaSlot slot, GaValue value, GaValue body) =>
            $"(({Slot(slot)} = {Expression(value)}), {Expression(body)}).Item2";

        private string Expression(GaValue value) => value switch
        {
            GaConstant constant => Constant(constant),
            GaLoad load => Load(load.Slot),
            GaBoundValue bound => StoreAndRead(bound.Slot, bound.Value, bound.Body),
            GaStoredValue stored => StoreAndRead(stored.Slot, stored.Value, stored.Body),
            GaBlockValue block => BlockValue(block),
            GaArrayRead read => ArrayRead(read),
            GaBufferRead read => BufferRead(read),
            GaBufferCount => "buffer.Count",
            GaSnapshotRead read => SnapshotRead(read),
            GaResourceRead read => ReadResource(read),
            GaHasOwn has => Presence(has.ComponentIndex),
            GaTryRead read => OptionalRead(read),
            GaCast cast => Convert(cast),
            GaUnary unary => Unary(unary),
            GaBinary binary => Binary(binary),
            GaSelect select => $"({Expression(select.Condition)} ? {Expression(select.True)} : {Expression(select.False)})",
            _ => throw new InvalidOperationException("Unknown GA IR value.")
        };

        private string BlockValue(GaBlockValue block)
        {
            int index = _blockValues.Count;
            _blockValues.Add(block);
            return $"__GaBlock{Number(index)}(ref {_faultState})";
        }

        private void EmitBlockValue(int index, GaBlockValue block)
        {
            _faultState = "__GaBlockFaults";
            Line($"{Scalar(block.Type)} __GaBlock{Number(index)}(ref __GaFaultState<{InputType}> {_faultState})");
            Open();
            Statement(block.Body);
            Line($"return {Expression(block.Result)};");
            Close();
            _faultState = "faults";
        }

        private string ReadResource(GaResourceRead read)
        {
            var field = program.TickResourceFields[read.FieldIndex];
            string access = field.Path.Length == 0 ? "tickResource" : GaFieldPath.CSharpAccess("tickResource", field.Path);
            return field.ClrEnumType is null ? access : $"(({Scalar(field.Type)}){access})";
        }

        private string OptionalRead(GaTryRead read)
        {
            string presence = Presence(read.ComponentIndex);
            if (read.Copies.Count == 0)
                return presence;
            int helper = _optionalReads.Count;
            _optionalReads.Add(read);
            string outputs = string.Join(", ", read.Copies.Select(copy => $"out {Slot(copy.Local)}"));
            return $"__GaTryRead{Number(helper)}({presence}, in component{Number(read.ComponentIndex)}, {outputs})";
        }

        private void EmitOptionalRead(int index, GaTryRead read)
        {
            var component = program.Components[read.ComponentIndex];
            string outputs = string.Join(", ", read.Copies.Select((copy, i) => $"out {Scalar(copy.Local.Type)} value{Number(i)}"));
            Line();
            Line($"private static bool __GaTryRead{Number(index)}(bool present, in {component.Id} component, {outputs})");
            Open();
            for (int i = 0; i < read.Copies.Count; i++)
            {
                var field = program.Fields[read.Copies[i].Field.Index];
                string access = GaFieldPath.CSharpAccess("component", field.Path);
                if (field.ClrEnumType != null)
                    access = $"({Scalar(field.Type)}){access}";
                Line($"value{Number(i)} = present ? {access} : default;");
            }
            Line("return present;");
            Close();
        }

        private static string Presence(int index) => "present" + Number(index);

        private string ArrayRead(GaArrayRead read)
        {
            var field = program.Fields[read.Field.FirstField];
            string access = FieldAccess(field, CheckedArrayIndex(read.Field, read.Index, read.Source));
            return field.ClrEnumType is not null ? $"({Scalar(field.Type)}){access}" : access;
        }

        private string CheckedArrayIndex(GaArrayField field, GaValue index, GaSourceSpan source) =>
            CheckedIndex(index, Number(field.Length), source);

        private string CheckedIndex(GaValue index, string length, GaSourceSpan source) =>
            FaultCall("CheckArrayIndex", "int", "int index, int length", $"{Expression(index)}, {length}",
                ["if (unchecked((uint)index) >= (uint)length)",
                    "    throw faults.Exception(global::SKECS.GA.GaFaultKind.IndexOutOfRange, ordinal, site);",
                    "return index;"], source);

        private string BufferRead(GaBufferRead read)
        {
            string args = $"{CheckedIndex(read.Index, "buffer.Count", read.Source)}, {Number(program.BufferOffsets[read.FieldIndex])}";
            return read.Type switch
            {
                GaScalar.Fixed => $"{FixedType}.FromRaw(unchecked((long)buffer.ReadWide({args})))",
                GaScalar.Bool => $"(buffer.ReadWord({args}) != 0u)",
                GaScalar.Int32 => $"unchecked((int)buffer.ReadWord({args}))",
                GaScalar.UInt32 => $"buffer.ReadWord({args})",
                _ => throw new InvalidOperationException("Unknown buffer scalar type.")
            };
        }

        private string SnapshotRead(GaSnapshotRead read)
        {
            string method = read.Type switch
            {
                GaScalar.Bool => "ReadBool",
                GaScalar.Int32 => "ReadInt32",
                GaScalar.UInt32 => "ReadUInt32",
                GaScalar.Fixed => "ReadFixed",
                _ => throw new InvalidOperationException("Unknown GA snapshot field type.")
            };
            string field = read.FieldIndex < 0 ? "" : $"{Number(read.FieldIndex)}, ";
            return $"snapshot{(UsesBuffer ? "!" : "")}.{method}({Expression(read.EntityId)}, {Expression(read.Generation)}, {field}{Expression(read.Fallback)})";
        }

        private string Convert(GaCast cast)
        {
            string operand = Expression(cast.Operand);
            if (cast.Operand.Type == cast.Type)
                return operand;
            if (cast.Type == GaScalar.Fixed)
                return $"{FixedType}.FromInt32({operand})";
            if (cast.Operand.Type == GaScalar.Fixed)
                return $"(int)({operand})";
            string target = Scalar(cast.Type);
            if (!cast.Checked)
                return $"({target})({operand})";

            string test = cast.Type == GaScalar.Int32 ? "value > int.MaxValue" : "value < 0";
            return FaultCall("Cast" + cast.Type, target, $"{Scalar(cast.Operand.Type)} value", operand,
                [$"if ({test})", "    throw faults.Exception(global::SKECS.GA.GaFaultKind.Overflow, ordinal, site);",
                    $"return ({target})value;"], cast.Source);
        }

        private string Unary(GaUnary unary)
        {
            string operand = Expression(unary.Operand);
            if (unary.Type == GaScalar.Fixed)
                return FixedFaultCall("NegateFixed", $"{FixedType} value", operand, "-value", unary.Source);
            if (unary.Checked)
            {
                return FaultCall("NegateInt32", "int", "int value", operand,
                    ["if (value == int.MinValue)", "    throw faults.Exception(global::SKECS.GA.GaFaultKind.Overflow, ordinal, site);",
                        "return -value;"], unary.Source);
            }
            var op = unary.Operator switch
            {
                GaUnaryOperator.Negate => "-",
                GaUnaryOperator.BitwiseNot => "~",
                GaUnaryOperator.Not => "!",
                _ => throw new InvalidOperationException("Unknown GA unary operator.")
            };
            return $"({op}({operand}))";
        }

        private string Binary(GaBinary binary)
        {
            var op = BinaryToken(binary.Operator);
            var left = Expression(binary.Left);
            var right = Expression(binary.Right);
            string args = $"{left}, {right}";
            string type = Scalar(binary.Left.Type);
            string names = $"{type} left, {type} right";
            string helper = binary.Operator.ToString() + binary.Left.Type;
            const string overflow = "    throw faults.Exception(global::SKECS.GA.GaFaultKind.Overflow, ordinal, site);";

            if (binary.Left.Type == GaScalar.Fixed)
                return binary.Type == GaScalar.Fixed
                    ? FixedFaultCall(helper, names, args, $"left {op} right", binary.Source)
                    : $"({left} {op} {right})";

            if (binary.Operator is GaBinaryOperator.Divide or GaBinaryOperator.Remainder)
            {
                var lines = new List<string>
                {
                    "if (right == 0)",
                    "    throw faults.Exception(global::SKECS.GA.GaFaultKind.DivideByZero, ordinal, site);"
                };
                if (binary.Left.Type == GaScalar.Int32)
                {
                    lines.Add("if (left == int.MinValue && right == -1)");
                    lines.Add(overflow);
                }
                lines.Add($"return left {op} right;");
                return FaultCall(helper, type, names, args, lines, binary.Source);
            }
            if (binary.Checked)
            {
                bool signed = binary.Left.Type == GaScalar.Int32;
                string wide = signed ? "long" : "ulong";
                string test = signed ? "value < int.MinValue || value > int.MaxValue" : "value > uint.MaxValue";
                return FaultCall(helper, type, names, args,
                    [$"{wide} value = unchecked(({wide})left {op} right);", $"if ({test})", overflow,
                        $"return ({type})value;"], binary.Source);
            }
            return $"({left} {op} {right})";
        }

        private string Site(GaSourceSpan source)
        {
            int index = _sources.Count;
            _sources.Add(source);
            return Number(index);
        }

        private string FaultCall(string name, string type, string parameters, string arguments, IReadOnlyList<string> lines,
            GaSourceSpan source)
        {
            _helpers.TryAdd(name, new FaultHelper(type, parameters, lines));
            return $"__Ga{name}({arguments}, ref {_faultState}, {Site(source)})";
        }

        private string FixedFaultCall(string name, string parameters, string arguments, string calculation, GaSourceSpan source)
        {
            return FaultCall(name, FixedType, parameters, arguments,
                ["try", "{", $"    return {calculation};", "}",
                    "catch (global::System.ArithmeticException error) when (error is global::System.OverflowException or global::System.DivideByZeroException)",
                    "{", "    var kind = error is global::System.OverflowException",
                    "        ? global::SKECS.GA.GaFaultKind.Overflow : global::SKECS.GA.GaFaultKind.DivideByZero;",
                    "    throw faults.Exception(kind, ordinal, site);", "}"], source);
        }

        private void FaultInfrastructure()
        {
            Line();
            Line("private static readonly global::SKECS.GA.GaSourceSpan[] __GaSources = new global::SKECS.GA.GaSourceSpan[]");
            Open();
            foreach (var source in _sources)
                Line($"new global::SKECS.GA.GaSourceSpan({Literal(source.File)}, {Number(source.Start)}, {Number(source.Length)}),");
            Close("};");
            Line();
            Line("private ref struct __GaFaultState<TInput> where TInput : unmanaged");
            Open();
            Line("private readonly global::SKECS.DeterministicJob<TInput> job;");
            Line("private readonly int row;");
            Line("internal ulong EvaluationOrdinal;");
            Line();
            Line("internal __GaFaultState(global::SKECS.DeterministicJob<TInput> job, int row)");
            Open();
            Line("this.job = job;");
            Line("this.row = row;");
            Line("EvaluationOrdinal = 0ul;");
            Close();
            Line();
            Line("internal global::SKECS.GA.GaExecutionException Exception(global::SKECS.GA.GaFaultKind kind, ulong ordinal, int site)");
            Open();
            Line("var entity = job.GetEntity(row);");
            Line($"return new global::SKECS.GA.GaExecutionException({Literal(program.SystemId)}, job.TickIndex, job.Stage, job.SystemOrder,");
            Line("    job.KernelOrder, job.GetSourceOrderOrdinal(row), entity.Id, entity.Version,");
            Line("    new global::SKECS.GA.GaKernelFault(kind, ordinal, __GaSources[site]), job.GetSourceOrderKey(row));");
            Close();
            Close();

            foreach (var (name, helper) in _helpers)
            {
                Line();
                Line($"private static {helper.Type} __Ga{name}<TInput>({helper.Parameters}, ref __GaFaultState<TInput> faults, int site)");
                Line("    where TInput : unmanaged");
                Open();
                Line("ulong ordinal = unchecked(faults.EvaluationOrdinal++);");
                foreach (var code in helper.Lines)
                    Line(code);
                Close();
            }
        }

        private string Load(GaSlot slot)
        {
            string access = Slot(slot);
            return slot.IsField && program.Fields[slot.Index].ClrEnumType != null ? $"({Scalar(slot.Type)}){access}" : access;
        }

        private string Slot(GaSlot slot)
        {
            if (!slot.IsField)
                return "local" + Number(slot.Index);
            return FieldAccess(program.Fields[slot.Index]);
        }

        private string FieldAccess(GaField field, string? index = null) =>
            GaFieldPath.CSharpAccess("component" + Number(_components[field.Component]), field.Path, index);

        private static string Constant(GaConstant constant) => constant.Type switch
        {
            GaScalar.Bool => constant.Bits == 0 ? "false" : "true",
            GaScalar.Int32 => $"unchecked((int)0x{unchecked((uint)constant.Bits).ToString("x8", CultureInfo.InvariantCulture)}u)",
            GaScalar.UInt32 => unchecked((uint)constant.Bits).ToString(CultureInfo.InvariantCulture) + "u",
            GaScalar.Fixed => $"{FixedType}.FromRaw(unchecked((long)0x{constant.Bits.ToString("x16", CultureInfo.InvariantCulture)}ul))",
            _ => throw new InvalidOperationException("Unknown GA scalar type.")
        };

        private static string Scalar(GaScalar type) => type switch
        {
            GaScalar.Bool => "bool",
            GaScalar.Int32 => "int",
            GaScalar.UInt32 => "uint",
            GaScalar.Fixed => FixedType,
            _ => throw new InvalidOperationException("Unknown GA scalar type.")
        };

        private static string BinaryToken(GaBinaryOperator op) => op switch
        {
            GaBinaryOperator.Add => "+",
            GaBinaryOperator.Subtract => "-",
            GaBinaryOperator.Multiply => "*",
            GaBinaryOperator.Divide => "/",
            GaBinaryOperator.Remainder => "%",
            GaBinaryOperator.BitwiseAnd => "&",
            GaBinaryOperator.BitwiseOr => "|",
            GaBinaryOperator.ExclusiveOr => "^",
            GaBinaryOperator.LeftShift => "<<",
            GaBinaryOperator.RightShift => ">>",
            GaBinaryOperator.UnsignedRightShift => ">>>",
            GaBinaryOperator.Equal => "==",
            GaBinaryOperator.NotEqual => "!=",
            GaBinaryOperator.Less => "<",
            GaBinaryOperator.LessOrEqual => "<=",
            GaBinaryOperator.Greater => ">",
            GaBinaryOperator.GreaterOrEqual => ">=",
            GaBinaryOperator.AndAlso => "&&",
            GaBinaryOperator.OrElse => "||",
            _ => throw new InvalidOperationException("Unknown GA binary operator.")
        };

        private void Open()
        {
            Line("{");
            _indent++;
        }

        private void Close(string text = "}")
        {
            _indent--;
            Line(text);
        }

        private void Line(string text = "")
        {
            if (text.Length != 0)
                _code.Append(' ', _indent * 4).Append(text);
            _code.Append('\n');
        }

        private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
        private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

        private sealed record FaultHelper(string Type, string Parameters, IReadOnlyList<string> Lines);
    }
