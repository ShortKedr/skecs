using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace SKECS.BenchmarkTools;

public static class BenchmarkCodeGenerator
{
    private const string Header = "// <auto-generated />\n// Generated by dotnet run --project SKECS.Benchmarks -- generate; edit CodeGen inputs.\n";
    private const string SharedDirectory = "SKECS.Benchmarks/Workloads";
    private static readonly UTF8Encoding Utf8 = new(false, true);
    private static readonly JsonSerializerOptions JsonOptions = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    public static int Run(string root, bool check)
    {
        root = Path.GetFullPath(root);
        var stale = new List<string>();
        var outputs = Outputs(root);
        foreach (var (path, content) in outputs)
        {
            var expected = Utf8.GetBytes(content);
            var actual = File.Exists(path) ? File.ReadAllBytes(path) : null;
            if (actual is null || !NormalizeNewlines(actual).AsSpan().SequenceEqual(expected))
                stale.Add(Path.GetRelativePath(root, path).Replace('\\', '/'));
            if (!check && (actual is null || !actual.AsSpan().SequenceEqual(expected)))
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllBytes(path, expected);
            }
        }
        if (check && stale.Count > 0)
        {
            Console.Error.WriteLine("Stale benchmark sources (run dotnet run --project SKECS.Benchmarks -- generate):");
            foreach (var path in stale) Console.Error.WriteLine(path);
            return 1;
        }
        Console.WriteLine($"Benchmark sources {(check ? "checked" : "generated")}: {outputs.Count} files");
        return 0;
    }

    private static byte[] NormalizeNewlines(byte[] bytes)
    {
        // Match Git's CRLF checkout normalization without ignoring BOMs, encoding,
        // trailing whitespace, or the final newline.
        using var result = new MemoryStream(bytes.Length);
        for (var i = 0; i < bytes.Length; i++)
        {
            if (bytes[i] == '\r' && i + 1 < bytes.Length && bytes[i + 1] == '\n') continue;
            result.WriteByte(bytes[i]);
        }
        return result.ToArray();
    }

    private static Dictionary<string, string> Outputs(string root)
    {
        var source = Path.Combine(root, "SKECS.Benchmarks", "CodeGen");
        using var model = JsonDocument.Parse(File.ReadAllText(Path.Combine(source, "benchmark-model.json"), Utf8));
        var catalog = model.RootElement;
        if (!catalog.GetProperty("shapeBits").TryGetInt32(out var bits) || bits is < 1 or > 8)
            throw new InvalidDataException("shapeBits must be between 1 and 8");
        var basicScenarios = Strings(catalog.GetProperty("basicScenarios"));
        var stressScenarios = Strings(catalog.GetProperty("stressScenarios"));
        var templates = Path.Combine(source, "Templates");
        var outputs = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var template in Directory.EnumerateFiles(templates, "*.cs.in", SearchOption.AllDirectories)
                     .OrderBy(path => Path.GetRelativePath(templates, path).Replace('\\', '/'), StringComparer.Ordinal))
        {
            var target = Path.Combine(root, Path.GetRelativePath(templates, template)[..^3]);
            var content = File.ReadAllText(template, Utf8).Replace("\r\n", "\n", StringComparison.Ordinal);
            content = content.Replace("{{BASIC_BENCHMARKS}}", string.Join("\n", basicScenarios.Select(name =>
                $"    [Benchmark] public void {name}() => _workload.{name}();")), StringComparison.Ordinal);
            content = content.Replace("{{STRESS_SETUP_TARGETS}}", string.Join(", ", stressScenarios
                .Where(name => name != "WideIteration").Select(name => $"nameof({name})")), StringComparison.Ordinal);
            content = content.Replace("{{STRESS_BENCHMARKS}}", string.Join("\n", stressScenarios.Select(name =>
                name is "RandomLookup" or "MixedFrames"
                    ? $"    [Benchmark] public long {name}() {{ _workload.Execute(nameof({name})); return _workload.Checksum; }}"
                    : $"    [Benchmark] public void {name}() => _workload.Execute(nameof({name}));")), StringComparison.Ordinal);
            outputs.Add(target, Render(content, bits));
        }
        var frameworks = catalog.GetProperty("frameworks").EnumerateArray().ToArray();
        string Registrations(string kind) => string.Join("\n", frameworks.Select(framework =>
            $"        ({Quote(framework.GetProperty("name").GetString()!)}, n => new {framework.GetProperty(kind).GetString()}(n)),"));
        outputs.Add(Path.Combine(root, "SKECS.Benchmarks", "Comparison", "BenchmarkRegistry.g.cs"), Header +
            "using SKECS.Benchmarks;\n\nstatic class BenchmarkRegistry\n{\n" +
            "    public static readonly (string Name, Func<int, IWorkload> Create)[] Basic =\n    [\n" +
            Registrations("basic") + "\n    ];\n" +
            "    public static readonly (string Name, Func<int, IStressBackend> Factory)[] Stress =\n    [\n" +
            Registrations("stress") + "\n    ];\n}\n");
        outputs.Add(Path.Combine(root, SharedDirectory, "BenchmarkModel.g.cs"), Header +
            "namespace SKECS.Benchmarks;\n\npublic static class BenchmarkModel\n{\n" +
            $"    public static readonly string[] BasicScenarios = [{string.Join(", ", basicScenarios.Select(Quote))}];\n" +
            $"    public static readonly string[] StressScenarios = [{string.Join(", ", stressScenarios.Select(Quote))}];\n" +
            "}\n");
        return outputs;
    }

    private static string[] Strings(JsonElement array) => array.EnumerateArray().Select(value => value.GetString()!).ToArray();
    private static string Quote(string value) => JsonSerializer.Serialize(value, JsonOptions);

    private static string Render(string template, int shapeBits)
    {
        template = Regex.Replace(template, @"\{\{TAGS\n(.*?)\nTAGS\}\}", match =>
            string.Join("\n", Enumerable.Range(1, shapeBits).Select(number => match.Groups[1].Value
                .Replace("$N", number.ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal)
                .Replace("$BIT", (1 << (number - 1)).ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal))),
            RegexOptions.Singleline);
        template = template.Replace("{{LAYOUT_COUNT}}", (1 << shapeBits).ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal);
        template = Regex.Replace(template, @"\{\{MOVE ([\w.]+) ([\w.]+) ([XYZ]+)\}\}", match =>
            string.Join(" ", match.Groups[3].Value.Select(axis => $"{match.Groups[1].Value}.{axis} += {match.Groups[2].Value}.{axis};")));
        template = template.Replace("{{INITIAL_POSITION_2D}}", "X = i, Y = i", StringComparison.Ordinal)
            .Replace("{{INITIAL_VELOCITY_2D}}", "X = 1, Y = -1", StringComparison.Ordinal);
        if (template.Contains("{{", StringComparison.Ordinal) || template.Contains("}}", StringComparison.Ordinal))
            throw new InvalidDataException("Unexpanded generator token");
        return Header + template.TrimEnd() + "\n";
    }
}
